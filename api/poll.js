// Pulls new Freshchat chats into the tracker without a webhook.
// Called every 15 minutes by .github/workflows/freshchat-sync.yml (or by hand):
//   curl -H "Authorization: Bearer $CRON_SECRET" https://<project>.vercel.app/api/poll
//
// Each run: (1) collects the Freshchat "Chat-Transcript" raw report requested on the previous run
// and adds/updates those chats, (2) requests the next report from where the last one ended,
// (3) re-checks a batch of recent untagged chats for L1/L2 added later in Freshchat.
import zlib from "node:zlib";
import {
  CFG, json, missingEnv, http, fcGet, fsGet, fsPatch, fsGetPath, fsSetPath, fsRecent, refreshTags,
  docId, partsText, channelLabel, ORDER_RE, clean, iso, loadRouter, upsertFromReport,
} from "./_lib.js";

const STATE = "config/poller";
const MAX_WINDOW_MS = 24 * 3600e3;      // catch up at most one day per report
const FIRST_LOOKBACK_MS = 3 * 3600e3;   // first run starts 3 hours back
const PENDING_TIMEOUT_MS = 3 * 3600e3;  // give up on a report that never finishes
const TAG_BATCH = 60;
// Firestore's free plan allows ~50,000 reads a day; these keep each 15-minute run light.
const TAG_CHECK_EVERY_MS = 60 * 60e3;   // re-check untagged chats once an hour
const TAG_WINDOW_MS = 36 * 3600e3;      // only chats from the last 36 hours
const TAG_SCAN_LIMIT = 250;
const started = () => Date.now();

// Any unexpected error is returned as readable JSON, so it shows up in the GitHub Actions log.
export async function GET(request) {
  try {
    return await run(request);
  } catch (e) {
    console.error("poll failed:", e && e.stack || e);
    return json({ ok: false, error: String((e && e.message) || e), hint: hintFor(String((e && e.message) || e)) }, 500);
  }
}

function hintFor(msg) {
  if (/Firestore (read|write|query) 403|PERMISSION_DENIED/i.test(msg)) return "Firestore refused access: TRACKER_KEY in Vercel must match the key in your Firestore rules exactly.";
  if (/Firestore .* 400.*API key|API_KEY_INVALID|API key not valid/i.test(msg)) return "FIREBASE_API_KEY in Vercel is wrong; copy apiKey from config.js.";
  if (/Firestore .* 404/i.test(msg)) return "Check FIREBASE_PROJECT_ID in Vercel (should be homerun-cs-tracker) and that the Firestore database exists.";
  if (/Freshchat 401|Freshchat 403/i.test(msg)) return "Freshchat refused FRESHCHAT_API_KEY; generate a new token and update it in Vercel.";
  if (/fetch failed|ENOTFOUND|getaddrinfo/i.test(msg)) return "A web address couldn't be reached; check FRESHCHAT_BASE in Vercel.";
  return "";
}

async function run(request) {
  const t0 = started();
  const secret = String(process.env.CRON_SECRET || "").trim();
  if (!secret || request.headers.get("authorization") !== "Bearer " + secret) return json({ ok: false, error: "unauthorized" }, 401);
  const missing = missingEnv();
  if (missing.length) return json({ ok: false, error: "Missing environment variables: " + missing.join(", ") }, 500);

  const out = { ok: true };
  let state = (await fsGetPath(STATE)) || {};
  // Assignment rules are read only when a run actually has chats to handle.
  let routerP = null;
  const getRouter = () => (routerP ||= loadRouter().catch((e) => { out.routing = "rules not loaded: " + e.message; return null; }));

  // 1) Collect the report requested last time
  if (state.pendingId) {
    try {
      const rep = await fcGet("/reports/raw/" + encodeURIComponent(state.pendingId));
      const status = String((rep && (rep.status || rep.state)) || "").toLowerCase();
      const links = rep ? collectLinks(rep) : [];
      if (!rep || /fail|error|cancel/.test(status)) {
        out.report = "failed, will request this window again";
        state = { ...state, pendingId: "", pendingStart: "", pendingEnd: "" };
      } else if (links.length && !/progress|pending|queued|process/.test(status)) {
        const rows = [];
        for (const link of links) rows.push(...(await downloadCsvRows(link)));
        const res = await importRows(rows, t0, rows.length ? await getRouter() : null);
        out.report = { window: [state.pendingStart, state.pendingEnd], messages: rows.length, ...res };
        state = { ...state, lastEnd: state.pendingEnd, pendingId: "", pendingStart: "", pendingEnd: "", pendingFailures: 0, lastImportAt: new Date().toISOString() };
      } else if (Date.now() - Date.parse(state.pendingRequestedAt || 0) > PENDING_TIMEOUT_MS) {
        out.report = "timed out, will request this window again";
        state = { ...state, pendingId: "", pendingStart: "", pendingEnd: "" };
      } else {
        out.report = "still being generated by Freshchat (" + (status || "no status yet") + ")";
      }
    } catch (e) {
      // A report whose download keeps failing (for example because its link has expired) is dropped
      // after 2 failed tries or 3 hours, and the same time window is requested again with fresh links.
      const fails = (Number(state.pendingFailures) || 0) + 1;
      const stale = fails >= 2 || Date.now() - Date.parse(state.pendingRequestedAt || 0) > PENDING_TIMEOUT_MS;
      out.report = "couldn't collect: " + e.message + (stale ? "; requesting this window again" : "; will retry once");
      state = stale ? { ...state, pendingId: "", pendingStart: "", pendingEnd: "", pendingFailures: 0 } : { ...state, pendingFailures: fails };
    }
    await fsSetPath(STATE, state);
  }

  // 2) Request the next report
  if (!state.pendingId) {
    const end = new Date(Date.now() - 2 * 60e3);
    let start = state.lastEnd ? new Date(state.lastEnd) : new Date(end - FIRST_LOOKBACK_MS);
    const windowEnd = new Date(Math.min(+end, +start + MAX_WINDOW_MS));
    if (windowEnd - start >= 60e3) {
      const r = await http(CFG.fcBase + "/reports/raw", {
        method: "POST",
        headers: { Authorization: "Bearer " + CFG.fcKey, "content-type": "application/json", Accept: "application/json" },
        body: JSON.stringify({ start: start.toISOString(), end: windowEnd.toISOString(), event: "Chat-Transcript", format: "csv" }),
      }, 1);
      const body = await r.json().catch(() => ({}));
      const id = body.id || body.request_id || ((body.link && body.link.href) || "").split("/").pop();
      if (r.ok && id) {
        state = { ...state, pendingId: id, pendingStart: start.toISOString(), pendingEnd: windowEnd.toISOString(), pendingRequestedAt: new Date().toISOString(), pendingFailures: 0 };
        await fsSetPath(STATE, state);
        out.requested = { id, window: [state.pendingStart, state.pendingEnd] };
      } else {
        out.requested = `Freshchat didn't accept the report request (HTTP ${r.status}${r.status === 429 ? ", one request per minute" : ""}): ${JSON.stringify(body).slice(0, 200)}`;
      }
    }
  }

  // 3) Once an hour, re-check recent untagged chats for L1/L2 added later in Freshchat
  if (Date.now() - Date.parse(state.lastTagCheckAt || 0) < TAG_CHECK_EVERY_MS) { out.tags = "next check within the hour"; console.log(JSON.stringify(out)); return json(out); }
  try {
    const since = new Date(Date.now() - TAG_WINDOW_MS).toISOString();
    const todo = (await fsRecent(since, TAG_SCAN_LIMIT))
      .filter((t) => t.convId && !t.l1 && !t.tagManual)
      .sort((a, b) => String(a.syncedAt || "").localeCompare(String(b.syncedAt || "")))
      .slice(0, TAG_BATCH);
    const router = todo.length ? await getRouter() : null;
    let tagged = 0, i = 0;
    const worker = async () => {
      while (i < todo.length && Date.now() - t0 < 270e3) { const t = todo[i++]; try { if (await refreshTags(t, router)) tagged++; } catch (e) { console.error(t.id, e.message); } }
    };
    await Promise.all([worker(), worker(), worker(), worker()]);
    out.tags = { checked: Math.min(i, todo.length), newlyTagged: tagged };
    state = { ...state, lastTagCheckAt: new Date().toISOString() };
    await fsSetPath(STATE, state);
  } catch (e) {
    out.tags = "skipped: " + e.message;
  }

  console.log(JSON.stringify(out));
  return json(out);
}

/* ---------- report download ---------- */
function collectLinks(o, acc = []) {
  if (typeof o === "string") { if (/^https?:\/\//.test(o) && !/\/reports\/raw\//.test(o)) acc.push(o); }
  else if (Array.isArray(o)) o.forEach((v) => collectLinks(v, acc));
  else if (o && typeof o === "object") Object.values(o).forEach((v) => collectLinks(v, acc));
  const score = (u) => (/\.(zip|csv)(\?|$)/i.test(u) ? 0 : /amazonaws|storage\.googleapis|blob\.core|cloudfront/i.test(u) ? 1 : 2);
  return [...new Set(acc)].sort((a, b) => score(a) - score(b)).filter((u, i, all) => score(u) < 2 || all.every((x) => score(x) === 2));
}

async function downloadCsvRows(url) {
  let r = await http(url);
  if (r.status >= 400 && r.status < 500 && /freshchat|freshworks/i.test(new URL(url).host)) r = await http(url, { headers: { Authorization: "Bearer " + CFG.fcKey } });
  if (!r.ok) {
    const txt = (await r.text().catch(() => "")).replace(/\s+/g, " ");
    const code = (txt.match(/<Code>([^<]+)<\/Code>/) || [])[1] || "";
    const u = new URL(url);
    throw new Error(`report download HTTP ${r.status}${code ? " " + code : ""} from ${u.host}${u.pathname.slice(0, 60)}${!code && txt ? " · " + txt.slice(0, 120) : ""}`);
  }
  let buf = Buffer.from(await r.arrayBuffer());
  const texts = buf[0] === 0x50 && buf[1] === 0x4b ? unzip(buf) : [buf.toString("utf8")];
  return texts.flatMap(parseCsv);
}

// Minimal ZIP reader (stored + deflate), enough for Freshchat report archives.
function unzip(buf) {
  let eocd = -1;
  for (let i = buf.length - 22; i >= Math.max(0, buf.length - 65557); i--) if (buf.readUInt32LE(i) === 0x06054b50) { eocd = i; break; }
  if (eocd < 0) throw new Error("report archive is not a valid zip");
  const count = buf.readUInt16LE(eocd + 10);
  let p = buf.readUInt32LE(eocd + 16);
  const files = [];
  for (let n = 0; n < count; n++) {
    const method = buf.readUInt16LE(p + 10), size = buf.readUInt32LE(p + 20);
    const nameLen = buf.readUInt16LE(p + 28), extraLen = buf.readUInt16LE(p + 30), commentLen = buf.readUInt16LE(p + 32);
    const local = buf.readUInt32LE(p + 42);
    const name = buf.toString("utf8", p + 46, p + 46 + nameLen);
    const dataStart = local + 30 + buf.readUInt16LE(local + 26) + buf.readUInt16LE(local + 28);
    const data = buf.subarray(dataStart, dataStart + size);
    if (/\.csv$/i.test(name)) files.push((method === 8 ? zlib.inflateRawSync(data) : data).toString("utf8"));
    p += 46 + nameLen + extraLen + commentLen;
  }
  return files;
}

// RFC 4180 CSV → array of objects keyed by header.
export function parseCsv(text) {
  text = text.replace(/^\uFEFF/, "");
  const rows = []; let row = [], field = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else q = false; }
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") { if (c === "\r" && text[i + 1] === "\n") i++; row.push(field); rows.push(row); row = []; field = ""; }
    else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const head = (rows.shift() || []).map((h) => h.trim());
  return rows.filter((r) => r.some((v) => v !== "")).map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ""])));
}

/* ---------- turning messages into tickets ---------- */
export function groupByConversation(rows) {
  rows = rows.slice().sort((a, b) => String(a.created_time).localeCompare(String(b.created_time)));
  const map = new Map();
  for (const r of rows) {
    const id = clean(r.conversation_id); if (!id) continue;
    let c = map.get(id);
    if (!c) map.set(id, (c = { convId: id, url: "", chan: "", src: "", first: "", msgs: [] }));
    if (!c.first) c.first = iso(r.created_time);
    if (!c.url && /^https?:\/\//.test(r.conversation_url || "")) c.url = r.conversation_url;
    if (!c.chan && r.channel_name) c.chan = r.channel_name;
    if (r.actor_type === "user" && (r.message_type || "normal") === "normal") {
      let parts; try { parts = JSON.parse(r.message_parts); } catch { parts = null; }
      const text = parts ? partsText(parts) : String(r.message_parts || "").trim();
      if (text) c.msgs.push({ t: iso(r.created_time), text });
      if (!c.src) c.src = r.message_source || "";
    }
  }
  return [...map.values()];
}

async function importRows(rows, t0, router) {
  const convs = groupByConversation(rows);
  let added = 0, updated = 0, skipped = 0, failed = 0, i = 0;
  const worker = async () => {
    while (i < convs.length && Date.now() - t0 < 200e3) {
      const c = convs[i++];
      try { const r = await upsertFromReport(c, router); r === "added" ? added++ : r === "updated" ? updated++ : skipped++; }
      catch (e) { failed++; console.error(c.convId, e.message); }
    }
  };
  await Promise.all([worker(), worker(), worker(), worker()]);
  return { conversations: convs.length, added, updated, skipped, failed, unfinished: convs.length - i };
}
